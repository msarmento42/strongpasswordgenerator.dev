import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const POSTS_DIR = 'src/posts';
const INDEX_PATH = path.join(POSTS_DIR, 'index.json');
const REPORT_PATH = 'docs/CONTENT_QUALITY_AUDIT.md';
const AFFILIATE_HOSTS = [
  'awin1.com',
  'kqzyfj.com',
  'nordpass.com',
  'nordvpn.com',
  'coveron.com',
];

function words(html = '') {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&[a-z#0-9]+;/gi, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean).length;
}

function links(html = '') {
  return [...html.matchAll(/href=["']([^"']+)["']/gi)].map((match) => match[1]);
}

function tokens(text = '') {
  return new Set(
    text
      .toLowerCase()
      .replace(/[^a-z0-9\s]/g, ' ')
      .split(/\s+/)
      .filter((token) => token.length > 2),
  );
}

function similarity(left, right) {
  const a = tokens(left);
  const b = tokens(right);
  const union = new Set([...a, ...b]);
  if (!union.size) return 0;
  let intersection = 0;
  for (const token of a) if (b.has(token)) intersection += 1;
  return intersection / union.size;
}

function escapeCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

async function readJson(file) {
  try {
    return JSON.parse(await readFile(file, 'utf8'));
  } catch (error) {
    throw new Error(`${file}: ${error.message}`);
  }
}

async function main() {
  const index = await readJson(INDEX_PATH);
  if (!Array.isArray(index)) throw new Error(`${INDEX_PATH} must contain an array`);

  const postFiles = (await readdir(POSTS_DIR))
    .filter((file) => file.endsWith('.json') && file !== 'index.json')
    .sort();
  const indexedSlugs = index.map((post) => post.slug);
  const duplicateSlugs = indexedSlugs.filter((slug, i) => indexedSlugs.indexOf(slug) !== i);
  if (duplicateSlugs.length) throw new Error(`Duplicate index slugs: ${[...new Set(duplicateSlugs)].join(', ')}`);

  const expectedFiles = new Set(indexedSlugs.map((slug) => `${slug}.json`));
  const missingFiles = [...expectedFiles].filter((file) => !postFiles.includes(file));
  const unindexedFiles = postFiles.filter((file) => !expectedFiles.has(file));
  if (missingFiles.length || unindexedFiles.length) {
    throw new Error(
      [`Missing indexed files: ${missingFiles.join(', ') || 'none'}`, `Unindexed post files: ${unindexedFiles.join(', ') || 'none'}`].join('\n'),
    );
  }

  const posts = [];
  for (const indexedPost of index) {
    const file = path.join(POSTS_DIR, `${indexedPost.slug}.json`);
    const post = await readJson(file);
    if (post.slug !== indexedPost.slug) throw new Error(`${file}: slug does not match index`);
    posts.push({ ...post, file });
  }

  const titles = posts.map((post) => post.title);
  const duplicateTitles = titles.filter((title, i) => titles.indexOf(title) !== i);
  if (duplicateTitles.length) throw new Error(`Duplicate titles: ${[...new Set(duplicateTitles)].join(', ')}`);

  const nearDuplicateMap = new Map();
  for (let i = 0; i < posts.length; i += 1) {
    for (let j = i + 1; j < posts.length; j += 1) {
      if (similarity(posts[i].excerpt, posts[j].excerpt) >= 0.85) {
        nearDuplicateMap.set(posts[i].slug, [...(nearDuplicateMap.get(posts[i].slug) || []), posts[j].slug]);
        nearDuplicateMap.set(posts[j].slug, [...(nearDuplicateMap.get(posts[j].slug) || []), posts[i].slug]);
      }
    }
  }

  const rows = posts.map((post) => {
    const description = post.description || post.metaDescription || '';
    const allLinks = links(post.content);
    const internalLinks = allLinks.filter((href) => href.startsWith('/'));
    const externalLinks = allLinks.filter((href) => /^https?:\/\//i.test(href));
    const affiliateLinks = externalLinks.filter((href) => AFFILIATE_HOSTS.some((host) => href.includes(host)));
    const sourceLinks = externalLinks.filter((href) => !AFFILIATE_HOSTS.some((host) => href.includes(host)));
    const wordCount = words(post.content);
    const flags = [];
    if (!description) flags.push('missing description');
    else if (description.length < 100) flags.push('short description');
    if (wordCount < 800) flags.push('thin (<800 words)');
    if (internalLinks.length < 2) flags.push('few internal links');
    if (!sourceLinks.length) flags.push('no external sources');
    if (nearDuplicateMap.has(post.slug)) flags.push(`near-duplicate excerpt: ${nearDuplicateMap.get(post.slug).join(', ')}`);
    return { post, wordCount, internalLinks: internalLinks.length, sourceLinks: sourceLinks.length, affiliateLinks: affiliateLinks.length, flags };
  });

  const count = (flag) => rows.filter((row) => row.flags.some((item) => item.startsWith(flag))).length;
  const lines = [
    '# SPG Content Quality Audit',
    '',
    'Generated by `npm run audit:content` from the repository content inventory.',
    '',
    '## Context',
    '',
    '- Search Console snapshot on 2026-07-27: **19 indexed pages** and **84 not indexed pages**.',
    '- These flags are triage signals. They do not automatically mean a page should be deleted or deindexed.',
    '- Production pages, article content, AdSense files, and affiliate URLs are not modified by this audit.',
    '',
    '## Summary',
    '',
    `- Indexed post records: **${rows.length}**`,
    `- Missing descriptions: **${count('missing description')}**`,
    `- Short descriptions: **${count('short description')}**`,
    `- Under 800 visible words: **${count('thin')}**`,
    `- Fewer than 2 internal links: **${count('few internal links')}**`,
    `- No non-affiliate external source links: **${count('no external sources')}**`,
    `- Near-duplicate excerpts: **${count('near-duplicate excerpt')}**`,
    '',
    '## Post inventory',
    '',
    '| Slug | Words | Internal | Sources | Affiliate | Flags |',
    '|---|---:|---:|---:|---:|---|',
    ...rows.map(({ post, wordCount, internalLinks, sourceLinks, affiliateLinks, flags }) =>
      `| ${escapeCell(post.slug)} | ${wordCount} | ${internalLinks} | ${sourceLinks} | ${affiliateLinks} | ${escapeCell(flags.join('; ') || 'none')} |`,
    ),
    '',
  ];

  await writeFile(REPORT_PATH, lines.join('\n'), 'utf8');
  console.log(`Audited ${rows.length} posts and wrote ${REPORT_PATH}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
